const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const { _electron } = require('playwright')
const { startFixture } = require('./controller-fixture.cjs')

async function run() {
  const fixture = await startFixture()
  const profile = await fs.mkdtemp(path.join(os.tmpdir(), 'gobot-desktop-smoke-'))
  const output = path.resolve(process.env.DESKTOP_QA_OUTPUT || 'test-results/desktop')
  await fs.mkdir(output, { recursive: true })
  let app, page
  const errors = []
  try {
    app = await _electron.launch({
      ...(process.env.DESKTOP_EXECUTABLE ? { executablePath: path.resolve(process.env.DESKTOP_EXECUTABLE), args: [] } : { args: [path.resolve('.')] }),
      env: { ...process.env, GOBOT_DESKTOP_USER_DATA: profile, GOBOT_DESKTOP_CONTROLLER: fixture.origin },
    })
    page = await app.firstWindow(); page.setDefaultTimeout(15000)
    page.on('pageerror', error => errors.push(error.message))
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1440, 998))
    await page.emulateMedia({ reducedMotion: 'reduce' })
    const initial = await page.evaluate(() => window.desktop.configuration())
    assert.equal(initial.controller, fixture.origin)
    await page.locator('input[autocomplete=username]').waitFor()
    assert.equal(await page.locator('input[type=url], input[type=checkbox]').count(), 0)
    await page.screenshot({ path: path.join(output, 'login.png'), scale: 'css' })
    await page.evaluate(() => { localStorage.setItem('go-bot.desktop-language', 'en') }); await page.reload()
    await page.locator('.language-picker select').selectOption('zh-CN')
    await page.waitForTimeout(150)
    assert.deepEqual(await app.evaluate(({ Menu }) => Menu.getApplicationMenu().items.map(item => item.label).filter(label => label !== 'Go Bot')), ['文件', '编辑', '视图', '窗口', '帮助'])
    assert.equal(await app.evaluate(({ Menu }) => Menu.getApplicationMenu().items.find(item => item.label === '编辑').submenu.items.find(item => item.role === 'copy').label), '复制')
    await page.locator('.language-picker select').selectOption('en')
    await page.waitForTimeout(150)
    assert.deepEqual(await app.evaluate(({ Menu }) => Menu.getApplicationMenu().items.map(item => item.label).filter(label => label !== 'Go Bot')), ['File', 'Edit', 'View', 'Window', 'Help'])
    await page.locator('input[autocomplete=username]').fill('desktop-fixture')
    await page.locator('button.account-submit').click()
    await page.getByText('desktop-plan.txt', { exact: true }).waitFor()
    await page.locator('textarea').fill('Check the streaming connection')
    await page.getByRole('button', { name: 'Send message', exact: true }).click()
    await page.getByText('Streaming reply received.', { exact: true }).waitFor()
    await page.screenshot({ path: path.join(output, 'chat.png') })
    assert.equal(fixture.streamCount, 1, 'one Host stream owns the workspace')
    await page.getByRole('button', { name: 'Tasks', exact: true }).click()
    await page.getByText('Review desktop implementation', { exact: true }).first().waitFor()
    await page.getByRole('button', { name: 'Plugin market', exact: true }).click()
    await page.getByText('Office tools', { exact: true }).waitFor()
    await page.locator('.plugin-mark img').first().waitFor()
    await page.waitForFunction(() => document.querySelector('.plugin-mark img')?.naturalWidth > 0)
    await page.getByRole('button', { name: 'Refresh extensions', exact: true }).click()
    await page.waitForTimeout(250)
    assert.ok(fixture.records.some(record => record.path === '/v1/settings/plugins' && record.search === '?refresh=true'))
    await page.getByRole('button', { name: 'Settings', exact: true }).click()
    await page.getByRole('heading', { name: 'Models', exact: true }).waitFor()
    assert.equal(fixture.streamCount, 1, 'navigation does not reconnect SSE')
    await page.getByRole('button', { name: 'Chats', exact: true }).click()
    await page.getByRole('button', { name: 'Actions for Project notes', exact: true }).waitFor()
    assert.equal(await page.locator('.chat-row').filter({ hasText: 'Go Bot' }).getByRole('button').count(), 1, 'main chat has no rename/delete action')
    await require('./sidebar-check.cjs').verifySidebar(page)
    await page.getByRole('button', { name: 'Actions for Project notes', exact: true }).click()
    await page.getByRole('menuitem', { name: 'Rename chat', exact: true }).click()
    const rename = page.getByRole('dialog', { name: 'Rename chat' })
    await rename.getByLabel('Chat title', { exact: true }).fill('')
    assert.ok(await rename.getByRole('button', { name: 'Save', exact: true }).isDisabled())
    await rename.getByLabel('Chat title', { exact: true }).fill('Desktop project')
    await rename.getByRole('button', { name: 'Save', exact: true }).click()
    await rename.waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: 'Actions for Desktop project', exact: true }).waitFor()
    fixture.sessions[1].title = 'Title from another client'
    fixture.emit('session', { seq: 500, type: 'session/title', data: { title: 'Title from another client' } }, fixture.ordinaryId)
    await page.getByRole('button', { name: 'Actions for Title from another client', exact: true }).waitFor()
    await page.locator('input[type=file]').first().setInputFiles({ name: 'note.txt', mimeType: 'text/plain', buffer: Buffer.from('Desktop attachment') })
    await page.locator('textarea').fill('Attachment transport')
    await page.getByRole('button', { name: 'Send message', exact: true }).click()
    await page.waitForTimeout(800)
    assert.deepEqual(fixture.uploads.map(({ name, content }) => ({ name, content })), [{ name: 'note.txt', content: 'Desktop attachment' }])
    const downloadPath = path.join(output, 'desktop-plan.txt')
    await app.evaluate(({ session }, filename) => session.defaultSession.once('will-download', (_event, item) => item.setSavePath(filename)), downloadPath)
    await page.getByRole('button', { name: /desktop-plan.txt/ }).click()
    await new Promise(async (resolve, reject) => {
      const started = Date.now()
      const poll = async () => { try { assert.equal(await fs.readFile(downloadPath, 'utf8'), 'Desktop plan\n'); resolve() } catch { if (Date.now() - started > 10000) reject(new Error('Download did not reach disk')); else setTimeout(poll, 50) } }
      await poll()
    })
    fixture.emit('questions.state', { questions: [{ callId: 'question-1', turn: 3, step: 1, questions: [{ id: 'style', question: 'Choose a response style', options: [{ label: 'Concise' }, { label: 'Detailed' }] }] }] })
    const question = page.getByRole('form', { name: 'Agent question' })
    await question.getByRole('radio', { name: 'Concise', exact: true }).check()
    await question.getByRole('button', { name: 'Send answer', exact: true }).click()
    await question.waitFor({ state: 'hidden' })
    assert.deepEqual(fixture.answers[0], { answers: [{ id: 'style', selected: ['Concise'] }] })
    fixture.emit('questions.state', { questions: [{ callId: 'approval-1', turn: 3, step: 1, questions: [], approval: { tool: 'write_file', toolCallId: 'tool-1', reason: 'Approve the requested test write?', detail: '/root/harness/plan.txt' } }] })
    const approval = page.getByRole('dialog', { name: 'Tool approval' })
    await approval.getByRole('button', { name: 'Deny', exact: true }).click()
    await approval.waitFor({ state: 'hidden' })
    assert.deepEqual(fixture.answers[1], { answers: [{ id: 'approval', selected: ['Deny'] }] })
    const oldCount = fixture.streamCount
    fixture.disconnect()
    await page.waitForTimeout(1300)
    assert.ok(fixture.streamCount > oldCount, 'stream reconnects after interruption')
    const identities = fixture.records.filter(record => record.path === '/v1/host/stream').map(record => JSON.parse(decodeURIComponent(record.headers['x-go-bot-client'])))
    assert.ok(identities.length >= 2)
    assert.ok(identities.every(identity => identity.type === 'desktop' && identity.id === identities[0].id))
    const saved = JSON.parse(await fs.readFile(path.join(profile, 'desktop.json'), 'utf8'))
    assert.equal(saved.clientId, identities[0].id)
    const api = fixture.records.filter(record => record.path.startsWith('/v1/') && record.path !== '/v1/capabilities')
    assert.ok(api.every(record => record.headers['x-user-id'] === 'desktop-fixture'))
    assert.ok(api.every(record => record.headers['x-go-bot-controller-origin'] === fixture.origin), 'all OAuth origins refer to the Controller')
    const isolation = await app.evaluate(({ BrowserWindow }) => { const settings = BrowserWindow.getAllWindows()[0].webContents.getLastWebPreferences(); return { sandbox: settings.sandbox, contextIsolation: settings.contextIsolation, nodeIntegration: settings.nodeIntegration } })
    assert.deepEqual(isolation, { sandbox: true, contextIsolation: true, nodeIntegration: false })
    assert.equal(await page.evaluate(() => typeof window.require), 'undefined')
    const hidden = await app.evaluate(({ BrowserWindow }) => { const win = BrowserWindow.getAllWindows()[0]; win.close(); return { visible: win.isVisible(), windows: BrowserWindow.getAllWindows().length } })
    assert.deepEqual(hidden, { visible: false, windows: 1 })
    await app.evaluate(({ app }) => app.emit('activate'))
    if (process.platform === 'darwin') assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible()), true)
    assert.equal(fixture.records.some(record => record.path === '/v1/host/stop'), false, 'closing a window never stops the Host')
    assert.deepEqual(errors, [])
    await app.close()
    const legacy = JSON.parse(await fs.readFile(path.join(profile, 'desktop.json'), 'utf8'))
    await fs.writeFile(path.join(profile, 'desktop.json'), JSON.stringify({ ...legacy, controller: 'https://previous.example.com', keepInTray: false }))
    app = await _electron.launch({
      ...(process.env.DESKTOP_EXECUTABLE ? { executablePath: path.resolve(process.env.DESKTOP_EXECUTABLE), args: [] } : { args: [path.resolve('.')] }),
      env: { ...process.env, GOBOT_DESKTOP_USER_DATA: profile, GOBOT_DESKTOP_CONTROLLER: '' },
    })
    page = await app.firstWindow()
    await page.locator('input[autocomplete=username]').waitFor()
    assert.equal((await page.evaluate(() => window.desktop.configuration())).controller, 'http://127.0.0.1:8080')
    assert.equal(await page.locator('input[type=url], input[type=checkbox]').count(), 0)
    const defaults = await app.evaluate(({ BrowserWindow }) => { const w = BrowserWindow.getAllWindows()[0]; w.close(); return { visible: w.isVisible(), windows: BrowserWindow.getAllWindows().length } })
    assert.deepEqual(defaults, { visible: false, windows: 1 })
    console.log('PASS: native Electron connection, login, HTTP/SSE, send, upload, download, tasks/plugins/settings, questions/approvals, reconnect, origin, isolation, tray lifecycle, client identity, renaming, remote plugin assets, sidebar resize and menu language')
  } catch (error) {
    if (page) { console.error(await page.locator('body').innerText().catch(() => '')); await page.screenshot({ path: path.join(output, 'failure.png') }).catch(() => {}) }
    throw error
  } finally { if (app) await app.close(); await fixture.close(); await fs.rm(profile, { recursive: true, force: true }) }
}
run().catch(error => { console.error(error); process.exitCode = 1 })
