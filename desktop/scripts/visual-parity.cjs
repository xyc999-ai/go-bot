const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const assert = require('node:assert/strict')
const { chromium, _electron } = require('playwright')
const { startFixture } = require('./controller-fixture.cjs')

async function run() {
  if (!process.env.WEB_REFERENCE_DIST) throw new Error('Set WEB_REFERENCE_DIST to an independently built Web dist directory.')
  const fixture = await startFixture({ webRoot: path.resolve(process.env.WEB_REFERENCE_DIST) })
  const profile = await fs.mkdtemp(path.join(os.tmpdir(), 'gobot-parity-'))
  const output = path.resolve(process.env.DESKTOP_QA_OUTPUT || 'test-results/visual')
  await fs.mkdir(output, { recursive: true })
  let browser, app
  try {
    browser = await chromium.launch({ ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}), headless: true })
    const web = await browser.newPage({ viewport: { width: 1440, height: 960 }, locale: 'en-US' })
    app = await _electron.launch({ args: [path.resolve('.')], env: { ...process.env, GOBOT_DESKTOP_USER_DATA: profile, GOBOT_DESKTOP_CONTROLLER: fixture.origin } })
    const desktop = await app.firstWindow()
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1440, 998))
    await desktop.waitForTimeout(500)
    const size = await desktop.evaluate(() => ({ width: innerWidth, height: innerHeight - 38 }))
    await web.setViewportSize(size)
    await web.goto(fixture.origin)
    const metrics = {}
    for (const [name, page] of [['web', web], ['desktop', desktop]]) {
      page.setDefaultTimeout(15000)
      await page.emulateMedia({ reducedMotion: 'reduce' })
      await page.evaluate(prefix => localStorage.setItem(prefix + '-language', 'en'), 'go-bot.' + (name === 'web' ? 'web' : 'desktop'))
      await page.reload()
      const capture = async state => {
        await page.mouse.move(1400, 940)
        await page.evaluate(() => document.activeElement?.blur())
        await page.waitForTimeout(400)
        await (name === 'desktop' ? page.locator('.desktop-content') : page.locator('body')).screenshot({ path: path.join(output, name + '-' + state + '.png'), animations: 'disabled', scale: 'css' })
      }
      await page.locator('input[autocomplete=username]').waitFor(); await capture('login')
      await page.locator('input[autocomplete=username]').fill('desktop-fixture')
      await page.locator('button.account-submit').click()
      await page.getByText('desktop-plan.txt', { exact: true }).waitFor(); await capture('chat')
      fixture.emit('questions.state', { questions: [{ callId: 'visual-question', turn: 2, step: 1, questions: [{ id: 'style', question: 'Choose a response style', options: [{ label: 'Concise' }, { label: 'Detailed' }] }] }] })
      await page.getByRole('form', { name: 'Agent question' }).waitFor(); await capture('question')
      fixture.emit('questions.state', { questions: [{ callId: 'visual-approval', turn: 2, step: 1, questions: [], approval: { tool: 'write_file', toolCallId: 'tool-1', reason: 'Approve the requested test write?', detail: '/root/harness/plan.txt' } }] })
      await page.getByRole('dialog', { name: 'Tool approval' }).waitFor(); await capture('approval')
      fixture.emit('questions.state', { questions: [] })
      await page.getByRole('dialog', { name: 'Tool approval' }).waitFor({ state: 'hidden' })
      await page.getByRole('button', { name: 'Chats', exact: true }).click(); await capture('sidebar')
      await page.getByRole('button', { name: 'Actions for Project notes', exact: true }).click()
      await page.getByRole('menuitem', { name: 'Rename chat', exact: true }).click()
      const rename = page.getByRole('dialog', { name: 'Rename chat' })
      await rename.waitFor(); await capture('rename')
      await rename.getByRole('button', { name: 'Cancel', exact: true }).click()
      metrics[name] = await page.evaluate(() => Object.fromEntries(['--rail-width', '--sidebar-width', '--files-width', '--content-width'].map(key => [key, getComputedStyle(document.documentElement).getPropertyValue(key).trim()])))
      await page.getByRole('button', { name: 'File system', exact: true }).first().click()
      await page.getByText('/root/harness', { exact: true }).first().waitFor(); await capture('files')
      await page.getByRole('button', { name: 'File system', exact: true }).first().click()
      await page.getByRole('button', { name: 'Tasks', exact: true }).click()
      await page.getByText('Review desktop implementation', { exact: true }).first().waitFor(); await capture('tasks')
      await page.getByRole('button', { name: 'Plugin market', exact: true }).click()
      await page.getByText('Office tools', { exact: true }).waitFor(); await capture('plugins')
      await page.getByRole('button', { name: 'Settings', exact: true }).click()
      await page.getByRole('heading', { name: 'Models', exact: true }).waitFor(); await capture('settings')
      await page.getByRole('button', { name: 'Switch to dark theme', exact: true }).click(); await capture('dark')
      // A narrower content viewport exercises the same right-panel overlay breakpoint.
      if (name === 'desktop') await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1024, 838))
      else await page.setViewportSize({ width: 1024, height: 800 })
      await capture('compact')
    }
    assert.deepEqual(metrics.web, metrics.desktop)
    await fs.writeFile(path.join(output, 'metrics.json'), JSON.stringify(metrics, null, 2))
    console.log('Captured paired Web/Electron screenshots and matching layout tokens:', output)
  } finally { if (app) await app.close(); if (browser) await browser.close(); await fixture.close(); await fs.rm(profile, { recursive: true, force: true }) }
}
run().catch(error => { console.error(error); process.exitCode = 1 })
