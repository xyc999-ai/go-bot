const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs/promises')
const { chromium } = require('playwright')
const { startFixture } = require('./controller-fixture.cjs')
const { verifySidebar } = require('./sidebar-check.cjs')
;(async () => {
  const fixture = await startFixture({ webRoot: path.resolve('../frontend/dist') })
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH, headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, locale: 'en-US' })
    await page.emulateMedia({ reducedMotion: 'reduce' }); await page.goto(fixture.origin)
    const login = async () => { await page.locator('input[autocomplete=username]').fill('desktop-fixture'); await page.locator('button.account-submit').click(); await page.getByText('desktop-plan.txt', { exact: true }).waitFor() }
    await login(); await page.getByRole('button', { name: 'Chats', exact: true }).click(); await verifySidebar(page)
    const separator = page.getByRole('separator', { name: 'Resize chat sidebar' })
    await separator.focus(); await separator.press('End'); await page.reload(); await login()
    await page.getByRole('button', { name: 'Chats', exact: true }).click()
    await separator.waitFor(); assert.equal(await separator.getAttribute('aria-valuenow'), '480')
    await page.getByRole('button', { name: 'File system', exact: true }).first().click()
    await page.getByRole('button', { name: 'Chats', exact: true }).click()
    await page.setViewportSize({ width: 1200, height: 900 }); await page.waitForTimeout(200)
    const layout = await page.evaluate(() => ({ sidebar: document.querySelector('#chat-sidebar').getBoundingClientRect().width, chat: document.querySelector('.workspace').getBoundingClientRect().width, overflow: document.documentElement.scrollWidth > innerWidth }))
    assert.equal(layout.sidebar, 336); assert.ok(layout.chat >= 480); assert.equal(layout.overflow, false)
    await fs.mkdir('test-results/sidebar', { recursive: true }); await page.screenshot({ path: 'test-results/sidebar/web-files.png' })
    await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(200)
    assert.equal(await separator.count(), 0, 'mobile overlay has no draggable splitter')
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    console.log('PASS Web: pointer/keyboard resize, chat and composer reflow, Escape/reset, persistence, file-panel limits and mobile overlay')
  } finally { await browser.close(); await fixture.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
